// Builds the compact glossary the AI reads from the research notes' tables:
// node scripts/glossary.mjs research/CONCEPTS.md src/sports/basketball-glossary.js
import { readFileSync, writeFileSync } from 'node:fs';
const [src, out] = process.argv.slice(2);
const rows = readFileSync(src, 'utf8').split('\n').filter(l => /^\| \*\*/.test(l)).map(l => l.split('|').slice(1, -1).map(c => c.trim()));
const clean = s => s.replace(/\*\*/g, '').replace(/\s*\[\d+\](\[\d+\])*/g, '').replace(/"/g, '');
const lines = rows.map(([term, coach, , heard]) => `${clean(term)}: ${clean(coach)}${heard ? ` (heard as: ${clean(heard)})` : ''}`);
writeFileSync(out, `// Generated by scripts/glossary.mjs from ${src}. Do not edit by hand.\nexport default ${JSON.stringify(lines.join('\n'))};\n`);
console.log(lines.length + ' terms → ' + out);
